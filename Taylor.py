# show_upload_box():
# Displays an Excel (.xlsx) file upload box for the user.
# Stops the application from continuing until a file is uploaded.
# Requirement: R1.

# load_orders(uploaded_file):
# Reads the uploaded Excel file and converts its data into orders.
# Calculates the Total for each order and warns the user about invalid rows.
# Requirements: R2 and R3.

# show_filters(orders):
# Displays Campus and Category filter options in the sidebar.
# Allows users to filter orders based on their selected choices.
# Requirement: R4.

# show_summary(shown):
# Displays three summary cards showing total sales, number of orders,
# and average order value.
# Also displays the best-selling item.
# Requirements: R5 and R6.

# show_orders_table(shown):
# Displays the filtered orders in a table.
# Includes all relevant order details and the calculated Total column.
# Requirement: R7.

# show_histogram(shown):
# Creates a bar chart showing the number of orders within each J$500 range.
# Helps users understand the distribution of order values.
# Requirement: R8.

# show_sales_by_item(shown):
# Creates a bar chart showing the total sales amount in Jamaican dollars
# for each item.
# Requirement: R9.

# show_sales_per_day(shown):
# Creates a line chart showing total sales for each day.
# Helps users track and compare daily sales performance.
# Stretch Requirement.

# show_download_button(shown):
# Displays a download button that allows users to export
# the currently filtered orders as a CSV file.
